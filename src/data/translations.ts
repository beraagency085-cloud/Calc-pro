export const getTranslation = (lang: string, key: keyof SectionTranslations): string => {
  if (UI_TRANSLATIONS[lang] && UI_TRANSLATIONS[lang][key]) {
    return UI_TRANSLATIONS[lang][key]!;
  }
  // Fallback to Bengali if exists, else English
  if (UI_TRANSLATIONS.bn && UI_TRANSLATIONS.bn[key]) {
    return UI_TRANSLATIONS.bn[key]!;
  }
  if (UI_TRANSLATIONS.en && UI_TRANSLATIONS.en[key]) {
    return UI_TRANSLATIONS.en[key]!;
  }
  return String(key);
};
